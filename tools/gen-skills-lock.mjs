#!/usr/bin/env node
// tools/gen-skills-lock.mjs — writes skills.lock.json; `--check` only reads it.
//
// The lock holds, per shipped skill under plugins/litclaude/skills, the SKILL.md size and hash, the
// file count, the folder bytes and one hash over every file, plus the `npm pack` file list. Those two
// halves (`skills`, `pack`) are generated. `budgets` is hand-owned: every run keeps it as written.
// A skill without a budget, or a budget whose skill is gone, is a violation until it is named:
// `--accept-new <id>` seeds a first budget from today's size and `--drop <id>` removes an orphan
// one (both repeatable, and naming a skill that is not new / not gone is a usage error). While any
// violation stands, nothing is written and the exit is 1.
//
// Only Git-tracked files count. A stray file in a skill folder never changes the lock, and an
// untracked file that npm would pack is a violation: it would ship, so it must be added or removed.
// Raise a budget by hand when a skill grows on purpose; lowering one is a reviewed hand edit.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { npmInvocation } from '../plugins/litclaude/lib/npm-invocation.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const LOCK_FILE = 'skills.lock.json';
export const SKILLS_DIR = 'plugins/litclaude/skills';
const NOTE =
  'Generated by npm run gen:skills-lock: skills and pack. Hand-owned and kept by every run: budgets. ' +
  'Check with npm run check:skills-lock.';
const HEADROOM = 1.5;

const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const byKey = (entries) => Object.fromEntries([...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

/** Repository-relative paths Git tracks that still exist on disk (a deleted tracked file is gone). */
export function trackedFiles(root = ROOT) {
  const result = spawnSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`git ls-files failed in ${root}: ${result.stderr || result.error?.message}`);
  return result.stdout.split('\0').filter(Boolean).filter((path) => existsSync(join(root, path)));
}

/** Per skill: SKILL.md bytes and hash, file count, folder bytes, and one hash over every file. */
export function measureSkills(root = ROOT, files = trackedFiles(root)) {
  const prefix = `${SKILLS_DIR}/`;
  const bySkill = new Map();
  for (const path of [...files].sort()) {
    if (!path.startsWith(prefix)) continue;
    const rest = path.slice(prefix.length);
    const slash = rest.indexOf('/');
    if (slash < 0) continue;
    const id = rest.slice(0, slash);
    if (!bySkill.has(id)) bySkill.set(id, []);
    bySkill.get(id).push(rest.slice(slash + 1));
  }
  const skills = [];
  for (const [id, rels] of bySkill) {
    if (!rels.includes('SKILL.md')) continue;
    const dir = join(root, SKILLS_DIR, id);
    const md = readFileSync(join(dir, 'SKILL.md'));
    let bytes = 0;
    const rows = rels.map((rel) => {
      const data = readFileSync(join(dir, rel));
      bytes += data.length;
      return `${sha256(data)} ${data.length} ${rel}\n`;
    });
    skills.push([id, { skillMd: { bytes: md.length, sha256: sha256(md) }, files: rels.length, bytes, sha256: sha256(rows.join('')) }]);
  }
  return byKey(skills);
}

/** `npm pack --dry-run --json --ignore-scripts` `[0].files[].path`, sorted. */
export function packList(root = ROOT) {
  const npm = npmInvocation(['pack', '--dry-run', '--json', '--ignore-scripts']);
  const result = spawnSync(npm.command, npm.args, { cwd: root, encoding: 'utf8', shell: npm.shell, maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`npm pack --dry-run failed (exit ${result.status}): ${result.stderr}`);
  return JSON.parse(result.stdout)[0].files.map((file) => file.path).sort();
}

const ceiling = (n) => Math.ceil((n * HEADROOM) / 1000) * 1000;

/** A first budget: today's SKILL.md size (rounded down to 100 B) and file count as floors, 1.5x as ceilings. */
export function seedBudget(skill) {
  return {
    minSkillBytes: Math.floor(skill.skillMd.bytes / 100) * 100,
    maxSkillBytes: ceiling(skill.skillMd.bytes),
    minFiles: skill.files,
    maxFiles: Math.ceil(skill.files * HEADROOM),
    maxBytes: ceiling(skill.bytes),
  };
}

export function budgetViolations(skills, budgets) {
  const out = [];
  for (const id of [...new Set([...Object.keys(skills), ...Object.keys(budgets)])].sort()) {
    const skill = skills[id];
    const budget = budgets[id];
    if (!budget) {
      out.push(`${id}: new skill without a budget (npm run gen:skills-lock -- --accept-new ${id})`);
      continue;
    }
    if (!skill) {
      out.push(`${id}: budget for a skill that is gone (npm run gen:skills-lock -- --drop ${id})`);
      continue;
    }
    const md = skill.skillMd.bytes;
    if (md < budget.minSkillBytes) out.push(`${id}: SKILL.md ${md} B is below its floor ${budget.minSkillBytes} B`);
    if (md > budget.maxSkillBytes) out.push(`${id}: SKILL.md ${md} B is above its ceiling ${budget.maxSkillBytes} B`);
    if (skill.files < budget.minFiles) out.push(`${id}: ${skill.files} files is below its floor ${budget.minFiles}`);
    if (skill.files > budget.maxFiles) out.push(`${id}: ${skill.files} files is above its ceiling ${budget.maxFiles}`);
    if (skill.bytes > budget.maxBytes) out.push(`${id}: ${skill.bytes} B in the folder is above its ceiling ${budget.maxBytes} B`);
  }
  return out;
}

/** Budgets are kept as written; only an id named in acceptNew is seeded and only one named in drop is removed. */
export function buildLock({ root = ROOT, pack, previous = {}, acceptNew = [], drop = [] }) {
  const skills = measureSkills(root);
  const kept = previous.budgets ?? {};
  for (const id of acceptNew) if (!skills[id] || kept[id]) throw new Error(`--accept-new ${id} names no new skill`);
  for (const id of drop) if (skills[id] || !kept[id]) throw new Error(`--drop ${id} names no gone skill`);
  const budgets = Object.entries(kept).filter(([id]) => !drop.includes(id));
  for (const id of acceptNew) budgets.push([id, seedBudget(skills[id])]);
  return { note: NOTE, budgets: byKey(budgets), skills, pack: [...pack].sort() };
}

export const readLock = (path = join(ROOT, LOCK_FILE)) => JSON.parse(readFileSync(path, 'utf8'));
export const renderLock = (lock) => `${JSON.stringify(lock, null, 2)}\n`;

/** Pack paths that would ship but are not tracked: refused, never pinned. */
const untrackedPack = (pack, tracked) => pack.filter((path) => !tracked.has(path)).map((path) => `pack: ${path} would ship, but Git does not track it`);

/** Read-only comparison of the lock with the tree: violations (budgets, untracked pack files) and drift (stale rows). */
export function checkLock(root = ROOT, { lock = readLock(join(root, LOCK_FILE)), pack = packList(root) } = {}) {
  const tracked = new Set(trackedFiles(root));
  const fresh = buildLock({ root, pack: pack.filter((path) => tracked.has(path)), previous: lock });
  const violations = [...untrackedPack(pack, tracked), ...budgetViolations(fresh.skills, fresh.budgets)];
  const drift = [];
  const ids = [...new Set([...Object.keys(fresh.skills), ...Object.keys(lock.skills ?? {})])].sort();
  for (const id of ids) if (JSON.stringify(fresh.skills[id]) !== JSON.stringify(lock.skills?.[id])) drift.push(`skill ${id}`);
  const pinned = new Set(lock.pack ?? []);
  for (const path of fresh.pack) if (!pinned.has(path)) drift.push(`pack +${path}`);
  for (const path of pinned) if (!fresh.pack.includes(path)) drift.push(`pack -${path}`);
  if (!drift.length && renderLock(fresh) !== renderLock(lock)) drift.push('note or layout');
  return { violations, drift };
}

function parseArgs(argv) {
  const options = { root: ROOT, check: false, pack: true, acceptNew: [], drop: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const value = () => {
      const next = argv[i + 1];
      if (!next || next.startsWith('--')) throw new Error(`${arg} needs a value`);
      i += 1;
      return next;
    };
    if (arg === '--check') options.check = true;
    else if (arg === '--no-pack') options.pack = false;
    else if (arg === '--root') options.root = resolve(value());
    else if (arg === '--accept-new') options.acceptNew.push(value());
    else if (arg === '--drop') options.drop.push(value());
    else throw new Error(`unknown argument: ${arg}`);
  }
  if (options.check && (options.acceptNew.length || options.drop.length)) throw new Error('--check takes no --accept-new or --drop');
  return options;
}

function main(argv) {
  const options = parseArgs(argv);
  const lockPath = join(options.root, LOCK_FILE);
  const previous = existsSync(lockPath) ? readLock(lockPath) : {};
  const pack = options.pack ? packList(options.root) : previous.pack ?? [];

  if (options.check) {
    if (!existsSync(lockPath)) {
      process.stdout.write(`${LOCK_FILE} is missing: run npm run gen:skills-lock\n`);
      return 1;
    }
    const { violations, drift } = checkLock(options.root, { lock: previous, pack });
    for (const line of violations) process.stdout.write(`violation: ${line}\n`);
    if (drift.length) process.stdout.write(`${LOCK_FILE} is stale: ${drift.join(', ')} (run npm run gen:skills-lock)\n`);
    if (violations.length || drift.length) return 1;
    process.stdout.write(`${LOCK_FILE}: current (${Object.keys(previous.skills).length} skills, ${previous.pack.length} packed files)\n`);
    return 0;
  }

  const tracked = new Set(trackedFiles(options.root));
  const lock = buildLock({ root: options.root, pack: pack.filter((path) => tracked.has(path)), previous, acceptNew: options.acceptNew, drop: options.drop });
  const violations = [...untrackedPack(pack, tracked), ...budgetViolations(lock.skills, lock.budgets)];
  if (violations.length) {
    process.stdout.write(`${LOCK_FILE} not written: ${violations.length} violation(s)\n${violations.join('\n')}\n`);
    return 1;
  }
  const text = renderLock(lock);
  const same = existsSync(lockPath) && readFileSync(lockPath, 'utf8') === text;
  if (!same) writeFileSync(lockPath, text);
  for (const id of options.acceptNew) {
    const b = lock.budgets[id];
    process.stdout.write(`seeded budget: ${id} (SKILL.md ${b.minSkillBytes}-${b.maxSkillBytes} B, ${b.minFiles}-${b.maxFiles} files, ${b.maxBytes} B in the folder)\n`);
  }
  for (const id of options.drop) process.stdout.write(`dropped budget: ${id}\n`);
  process.stdout.write(`${LOCK_FILE}: ${same ? 'already current' : 'updated'} (${Object.keys(lock.skills).length} skills, ${lock.pack.length} packed files)\n`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`gen-skills-lock: ${error.message}\n`);
    process.exitCode = 2;
  }
}
